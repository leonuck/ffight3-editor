function buildGfxScript(opts, palSnesAddr) {
  const bytes = [];
  bytes.push(0x4D, 0xE0, 0x6E, 0xC5, 0x00, 0x00, 0x7F);
  bytes.push(0x44, 0x00, 0x00, 0x7F, 0x00, 0x00, 0x00, 0x80);
  bytes.push(0x4D, 0x80, 0x8A, 0xCA, 0x00, 0x80, 0x7E);
  bytes.push(0x44, 0x00, 0xA0, 0x7E, 0x00, 0x40, 0x00, 0x10);
  bytes.push(0x44, 0x00, 0x80, 0x7E, 0x00, 0x48, 0x00, 0x10);
  bytes.push(0x4D, 0xE0, 0xCA, 0xCB, 0x00, 0x20, 0x7E);

  if (opts.layout === 'arena') {
    bytes.push(0x44, 0x00, 0x50, 0xCE, 0xAC, 0x42, 0x40, 0x00);
    bytes.push(0x44, 0x00, 0x50, 0xCE, 0xAC, 0x46, 0x40, 0x00);
  }

  const p0 = palSnesAddr & 0xFF;
  const p1 = (palSnesAddr >> 8) & 0xFF;
  const p2 = (palSnesAddr >> 16) & 0xFF;
  bytes.push(0x43, p0, p1, p2, 0xC0, 0x00, 0x20, 0x00);
  bytes.push(0x45);

  return Buffer.from(bytes);
}

// Test writing to rom copy
const testRom = Buffer.from(rom);
const s44Off = 0x342B3 + h;
const s44MetaOff = 0x0D35 + (44 - 1) * 12 + h;

// Suppose we allocate in FREE_RUNS at 0xE55A8
let allocP = 0xE55A8;

// 1. Palette
const palTheme = 'blue';
let palSnes = 0xC36482;
if (palTheme !== 'classic' && PALETTES[palTheme]) {
  const palBytes = Buffer.from(PALETTES[palTheme]);
  testRom.set(palBytes, allocP + h);
  palSnes = 0xC00000 + allocP;
  allocP += palBytes.length;
}

// 2. Script
const script = buildGfxScript({ layout: 'arena' }, palSnes);
testRom.set(script, allocP + h);
const scriptSnes = 0xC00000 + allocP;
allocP += script.length;

// 3. Write Pointers to Stage 44 (0x342B3)
// Pointer 0: C3:4593
testRom[s44Off + 0] = 0x93; testRom[s44Off + 1] = 0x45; testRom[s44Off + 2] = 0xC3;
// Pointer 1: Custom GFX Loader Script!
testRom[s44Off + 3] = scriptSnes & 0xFF;
testRom[s44Off + 4] = (scriptSnes >> 8) & 0xFF;
testRom[s44Off + 5] = (scriptSnes >> 16) & 0xFF;
// Pointer 2: Object list: if arena, C3:A8B5 (clean, no tables), else C3:A314
testRom[s44Off + 6] = 0xB5; testRom[s44Off + 7] = 0xA8; testRom[s44Off + 8] = 0xC3;
// Pointer 3: C3:95C0
testRom[s44Off + 9] = 0xC0; testRom[s44Off + 10] = 0x95; testRom[s44Off + 11] = 0xC3;
// Terminator
testRom[s44Off + 15] = 0x00;

// 4. Metadata: BGM
testRom[s44MetaOff + 0] = 0x0A; // Boss music!

console.log('✓ Stage 44 GFX script injected at SNES', scriptSnes.toString(16).toUpperCase());
console.log('✓ Stage 44 Palette injected at SNES', palSnes.toString(16).toUpperCase());
console.log('✓ Stage 44 Pointer 1 set to:', (testRom[s44Off+3] | (testRom[s44Off+4]<<8) | (testRom[s44Off+5]<<16)).toString(16).toUpperCase());
console.log('✓ Stage 44 Pointer 2 (Objects) set to:', (testRom[s44Off+6] | (testRom[s44Off+7]<<8) | (testRom[s44Off+8]<<16)).toString(16).toUpperCase());
console.log('✓ Stage 44 BGM set to: 0x' + testRom[s44MetaOff].toString(16));

